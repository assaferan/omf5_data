"""
Rewrite the Hecke ring bases that do not start with 1, as the classical forms' bases.

The LMFDB pages show eigenvalues in a basis 1, beta_1, ..., beta_{d-1} of the Hecke
ring, printing the first coordinate as the constant term; every basis of the classical
forms (mf_hecke_nf) starts with 1 and keeps the coordinates of the a_n small.
parse_omf5, recompute_hecke_rings.py and add_coordinates_14_20.py stored Sage's basis of
the order, which need not start with 1.  This replaces such a basis by reduced_basis, a
basis of the same lattice that starts with 1: the other elements LLL-reduced against the
coordinates of the eigenvalues lambda_p (in the order of p), ordered and signed by the
first eigenvalue they appear in (so that lambda_2 = beta_1 + c where possible), and
shifted by integers to make the constant coordinates small.  It rewrites lambda_p and lambda_p_square in it, checking that:
  - the stored basis and its stored inverse are inverse to each other;
  - the new basis spans the same lattice (the change of basis is in GL_d(Z));
  - every eigenvalue is the same field element before and after.
Orbits with non-integral coordinates (their stored basis is not the ring generated by their
eigenvalues; there were 137 in data_nl_200 until recompute_nl_200_rings.py) are left
unchanged and reported.  A file is
rewritten only if one of its records changes, and only after checking that the unchanged
file is reproduced exactly from what was read.

Usage:
    sage -python rebasis_hecke_rings.py DIR [DIR ...]      # e.g. hecke_evs_3_0/data hecke_evs_3_0/data_nl_200
"""
import glob
import os
import re
import sys
from collections import Counter

from sage.all import Matrix, QQ, ZZ, block_diagonal_matrix, identity_matrix, lcm, prime_range, vector


def load(text):
    # the files are Python literals with integers, 'NULL', and a few fractions a/b
    # (a fraction is a list element: not the digits of a URL in related_objects)
    text = re.sub(r'(\d)L', r'\1', text)
    return eval(re.sub(r'(?<=[\[ -])(\d+)/(\d+)(?=[,\]])', r'QQ(\1)/\2', text), {'QQ': QQ})


def dump(entries):
    return str(entries)


def rows_of(nums, dens):
    return Matrix(QQ, [[QQ(c) / QQ(den) for c in num] for num, den in zip(nums, dens)])


def triangular(B):
    d = B.nrows()
    D = lcm([c.denominator() for c in B.list()])
    M = Matrix(ZZ, [[ZZ(c * D) for c in reversed(list(r))] for r in B.rows()]).echelon_form()
    T = Matrix(QQ, [list(reversed(list(r))) for r in reversed(M.rows())]) / D
    assert T.row(0) == vector(QQ, [1] + [0] * (d - 1)), "1 is not a primitive element of the lattice"
    return T


def reduced_basis(B, X):
    """The basis of the lattice spanned by the rows of B described above (as smf_lmfdb's
    db_tables/fix_hecke_ring_basis.reduced_basis); X: the eigenvalues as power-basis vectors,
    in the order of their index."""
    d = B.nrows()
    T = triangular(B)
    Tinv = T.inverse()
    E = Matrix(QQ, [vector(QQ, x) * Tinv for x in X])
    assert all(c in ZZ for c in E.list()), "an eigenvalue is not in the ring"
    E1 = E.matrix_from_columns(range(1, d))
    if E1.rank() < d - 1:
        # the eigenvalues generate the ring but do not span the field: add the ring's basis
        E = E.stack(identity_matrix(QQ, d))
        E1 = E.matrix_from_columns(range(1, d))
    m = next(i for i in range(1, E1.nrows() + 1) if E1.matrix_from_rows(range(i)).rank() == d - 1)
    m = min(E1.nrows(), m + d)
    P = E1.matrix_from_rows(range(m)).transpose().change_ring(ZZ)
    R, U = P.LLL(transformation=True)
    C = block_diagonal_matrix(identity_matrix(ZZ, 1), U.transpose())
    E2 = (E * C).matrix_from_rows(range(m))
    def first(i):
        col = E2.column(i)
        return min(r for r in range(m) if col[r])
    order = sorted(range(1, d), key=lambda i: (first(i), E2.column(i).norm()))
    S = Matrix(ZZ, d, d)
    S[0, 0] = 1
    for new_i, old_i in enumerate(order, 1):
        S[old_i, new_i] = 1 if E2[first(old_i), old_i] > 0 else -1
    C = C * S
    E2 = (E * C).matrix_from_rows(range(m))
    A, e0 = E2.matrix_from_columns(range(1, d)), E2.column(0)
    shift = (A.transpose() * A).solve_right(A.transpose() * e0)
    C2 = identity_matrix(ZZ, d)
    for i in range(1, d):
        C2[i, 0] = -(shift[i - 1] + QQ(1) / 2).floor()     # explicit rounding: Sage's default is changing
    Tn = (C * C2).inverse() * T
    assert Tn.row(0) == vector(QQ, [1] + [0] * (d - 1))
    return Tn


def eigenvalues(e, B):
    """lambda_p as power-basis vectors, in the order of p.  (Only lambda_p: these files store
    T(p,2) where the LMFDB stores T(p^2), and both bases must agree.)"""
    return [vector(QQ, [QQ(c) for c in v]) * B for v in e['lambda_p'] if v != 'NULL']


def as_cols(M):
    dens = [int(r.denominator()) for r in M.rows()]
    return [[int(c * den) for c in r] for r, den in zip(M.rows(), dens)], dens


def num(c):
    c = QQ(c)
    return int(c) if c in ZZ else c


def rebasis(e):
    """The entry in the triangular basis, or None if its basis already starts with 1."""
    d = len(e['field_poly']) - 1
    if d <= 1 or e.get('hecke_ring_power_basis') or not e.get('hecke_ring_numerators'):
        return None
    if e['hecke_ring_numerators'][0] == [1] + [0] * (d - 1) and e['hecke_ring_denominators'][0] == 1:
        return None
    B = rows_of(e['hecke_ring_numerators'], e['hecke_ring_denominators'])
    Binv = rows_of(e['hecke_ring_inverse_numerators'], e['hecke_ring_inverse_denominators'])
    assert B * Binv == 1, "the stored inverse basis is not the inverse"
    if any(QQ(c) not in ZZ for col in ('lambda_p', 'lambda_p_square') for v in e[col] if v != 'NULL' for c in v):
        return 'non-integral'
    T = reduced_basis(B, eigenvalues(e, B))
    Tinv = T.inverse()
    C = B * Tinv
    assert all(c in ZZ for c in C.list()) and abs(C.det()) == 1, "the new basis spans another lattice"
    new = dict(e)     # keeps the key order
    new['hecke_ring_numerators'], new['hecke_ring_denominators'] = as_cols(T)
    new['hecke_ring_inverse_numerators'], new['hecke_ring_inverse_denominators'] = as_cols(Tinv)
    for col in ('lambda_p', 'lambda_p_square'):
        out = []
        for v in e[col]:
            if v == 'NULL':
                out.append(v)
                continue
            w = vector(QQ, [QQ(c) for c in v]) * C
            assert w * T == vector(QQ, [QQ(c) for c in v]) * B
            out.append([num(c) for c in w])
        new[col] = out
    return new


def process(fname, stats):
    with open(fname) as f:
        text = f.read()
    nl = "\n" if text.endswith("\n") else ""
    entries = load(text)
    changed = 0
    for i, e in enumerate(entries):
        new = rebasis(e)
        if new == 'non-integral':
            stats['non-integral (unchanged)'] += 1
            continue
        if new is not None:
            entries[i] = new
            changed += 1
            stats[e.get('aut_rep_type')] += 1
    if changed:
        assert dump(load(text)) + nl == text, "%s is not reproduced from what was read" % fname
        with open(fname, 'w') as f:
            f.write(dump(entries) + nl)
    return changed


if __name__ == '__main__':
    for d in sys.argv[1:]:
        stats, files = Counter(), 0
        for fname in sorted(glob.glob(os.path.join(d, 'hecke_ev_3_0_*.dat'))):
            files += bool(process(fname, stats))
        print("%s: %d orbits in %d files rewritten %s" % (d, sum(stats.values()), files, dict(stats)), flush=True)
