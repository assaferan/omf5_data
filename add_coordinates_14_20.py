"""
Eigenvalue coordinates for the G orbits of dimension 14-20 of omf5_data
(hecke_evs_3_0/data), from runs of omf5 at precision 100:

    src/omf5 -genus=qf5db.sage -isom -nonlifts -disc=N -prec=100

For each such orbit, matched to the form of the run with the same field_poly and
traces of T(p,1), p < 100 (unique, and the traces of T(p,2) must agree):

  - the Hecke ring H: the order generated by the lambda_p and lambda_p_square,
    computed exactly (the closure of their Z-span under multiplication);
  - disc(H), factored completely, every prime factor proved prime;
  - the ring of integers O_K: the ring generated by H and pari's
    nfbasis([f, P]), P the primes p with p^2 | disc(H).  It is maximal at P
    (by nfbasis) and at every other prime (where H already is), so it is
    the ring of integers, with no need to factor disc(f), which is
    disc(O_K) [O_K : Z[a]]^2 and has hundreds of digits;
  - hecke_ring_index = [O_K : H], hecke_ring_generator_nbound as in
    recompute_hecke_rings.py, and the coordinates in Sage's basis of H;
  - the field: its discriminant disc(O_K) (factored with the primes of
    disc(H)) and the polredabs polynomial of pari's nfinit([f, basis of O_K]).

Writes OUTDIR/hecke_ev_3_0_N.dat (nothing else in the file changes) and
OUTDIR/fields_N.json, one record per orbit:
    {level, field_poly, hecke_ring_disc_factorization, field_disc,
     field_disc_factorization, polredabs}

    sage -python add_coordinates_14_20.py RUNDIR DATADIR OUTDIR N [N ...]

The runs used omf5 at commit a5ced0b (branch square-test of assaferan/omf5), built against FLINT 3.6.0.
"""
import json
import os
import re
import sys
import time

from sage.all import Matrix, PolynomialRing, QQ, ZZ, NumberField, lcm, pari, prime_range, sage_eval, sqrt, vector
from sage.rings.number_field.order import absolute_order_from_module_generators

B = 100
MIN_DEG, MAX_DEG = 14, 20
KEYS = ['hecke_ring_generator_nbound', 'lambda_p_square', 'hecke_ring_power_basis', 'hecke_ring_inverse_denominators',
        'field_poly', 'atkin_lehner_eigenvals', 'hecke_ring_inverse_numerators', 'trace_lambda_p', 'aut_rep_type',
        'lambda_p', 'hecke_ring_denominators', 'hecke_ring_numerators', 'atkin_lehner_string', 'hecke_ring_index',
        'trace_lambda_p_square']


def load(fname):
    with open(fname) as f:
        return eval(re.sub(r'(\d)L', r'\1', f.read()))


def run_forms(fname, N):
    """The forms of an omf5 run: (field_poly coefficients, F, lambda_p, lambda_p_square) as field elements."""
    Qx = PolynomialRing(QQ, 'x')
    good = [p for p in prime_range(B) if N % p]
    good_sq = [p for p in prime_range(sqrt(B)) if N % p]
    out = []
    for d, fs in load(fname).items():
        for f in fs:
            pol = Qx([int(c) for c in f['field_poly'].split()[1:]])
            if not MIN_DEG <= pol.degree() <= MAX_DEG:
                continue
            F = NumberField(pol, 'a')
            a = F.gen()
            assert len(f['lambda_p']) == len(good) and len(f['lambda_p_square']) == len(good_sq), (N, d)
            lp = {p: F(sage_eval(s, locals={'a': a})) for p, s in zip(good, f['lambda_p'])}
            lp2 = {p: F(sage_eval(s, locals={'a': a})) for p, s in zip(good_sq, f['lambda_p_square'])}
            out.append(([int(c) for c in pol.coefficients(sparse=False)], F, lp, lp2))
    return out


def ring_closure(F, rows):
    """Rows over QQ (power basis) of a Z-basis of the ring generated by 1 and the elements rows."""
    def hnf(rs):
        D = lcm([c.denominator() for r in rs for c in r])
        M = (Matrix(QQ, rs) * D).change_ring(ZZ).echelon_form()
        return [vector(QQ, r) / D for r in M.rows() if r]
    M = hnf([vector(QQ, list(F(1)))] + [vector(QQ, list(r)) for r in rows])
    while True:
        els = [F(list(r)) for r in M]
        new = hnf([vector(QQ, list(u * v)) for i, u in enumerate(els) for v in els[i:]] + M)
        if new == M:
            return M
        M = new


def triangular(rows):
    """The same lattice, with a basis b_0 = 1, b_1, ... in which b_i has degree i (as pari's nfinit wants)."""
    d = len(rows)
    D = lcm([c.denominator() for r in rows for c in r])
    M = Matrix(ZZ, [[ZZ(c * D) for c in reversed(list(r))] for r in rows]).echelon_form()
    out = [vector(QQ, list(reversed(list(r)))) / D for r in reversed(M.rows())]
    assert out[0] == vector(QQ, [1] + [0] * (d - 1)), "the lattice is not an order containing 1 as a primitive vector"
    assert all(r[i] != 0 and all(c == 0 for c in r[i + 1:]) for i, r in enumerate(out))
    return out


def disc(F, rows):
    els = [F(list(r)) for r in rows]
    return ZZ(Matrix(QQ, [[(x * y).trace() for y in els] for x in els]).det())


def proved_factorization(n):
    fac = [(ZZ(p), int(e)) for p, e in ZZ(n).factor(proof=False)]
    for p, e in fac:
        assert p.is_prime(proof=True), "%d is not prime" % p
    return fac


def orbit_data(N, F, lambda_p, lambda_p_square):
    """The new omf5_data fields of an orbit and its field record."""
    d = F.degree()
    a = F.gen()
    lam = [(i, x) for i, x in enumerate(lambda_p) if x != 'NULL']
    lam2 = [x for x in lambda_p_square if x != 'NULL']
    H_lam = ring_closure(F, [list(x) for _, x in lam])
    H = ring_closure(F, H_lam + [vector(QQ, list(x)) for x in lam2])
    assert len(H) == d, "the eigenvalues do not generate an order"
    # nbound: the first p_idx at which the lambda_p up to it generate H_lam
    dH_lam = disc(F, H_lam)
    nbound, M = None, []
    for i, x in lam:
        M = ring_closure(F, M + [vector(QQ, list(x))])
        if len(M) == d and disc(F, M) == dH_lam:
            nbound = i
            break
    assert nbound is not None
    dH = disc(F, H)
    fac = proved_factorization(abs(dH))
    P = [int(p) for p, e in fac if e >= 2]
    pol = F.polynomial()
    if P:
        O1 = [vector(QQ, [QQ(c) for c in pari(b).Vecrev()] + [0] * (d - len(pari(b).Vecrev())))
              for b in pari.nfbasis([pari(pol), P])]
        OK = ring_closure(F, O1 + H)
    else:
        OK = H
    dK = disc(F, OK)
    index = ZZ((dH / dK).sqrt())
    assert index**2 * dK == dH
    # the field
    nf = pari.nfinit([pari(pol), pari([pari(F(list(r)).polynomial()) for r in triangular(OK)])])
    assert ZZ(pari('(x) -> x.disc')(nf)) == dK, "nfinit disagrees on the discriminant"
    red = pari.polredabs(nf)
    red = [int(c) for c in pari(red).Vecrev()]
    rest, fdisc = abs(dK), []
    for p, e in fac:
        v = rest.valuation(p)
        if v:
            fdisc.append([int(p), int(v)])
            rest //= p**v
    assert rest == 1
    if dK < 0:
        fdisc = [[-1, 1]] + fdisc
    # Sage's basis of H, as parse_omf5 and recompute_hecke_rings.py
    O = absolute_order_from_module_generators([F(list(r)) for r in H], check_integral=False, check_rank=False,
                                              check_is_ring=False)
    mat = Matrix([list(b) for b in O.basis()])
    inv = mat**(-1)
    new = {
        'hecke_ring_generator_nbound': int(nbound),
        'hecke_ring_power_basis': False,
        'hecke_ring_denominators': [int(r.denominator()) for r in mat],
        'hecke_ring_numerators': [[int(c) for c in r.denominator() * r] for r in mat],
        'hecke_ring_inverse_denominators': [int(r.denominator()) for r in inv],
        'hecke_ring_inverse_numerators': [[int(c) for c in r.denominator() * r] for r in inv],
        'hecke_ring_index': int(index),
    }

    def to_lists(xs):
        out = []
        for x in xs:
            if x == 'NULL':
                out.append('NULL')
            else:
                v = (Matrix(QQ, [list(x)]) * inv).row(0)
                assert all(c in ZZ for c in v), "level %d: an eigenvalue is not in the Hecke ring" % N
                out.append([int(c) for c in v])
        return out
    new['lambda_p'] = to_lists(lambda_p)
    new['lambda_p_square'] = to_lists(lambda_p_square)
    basis = [sum(n * a**i for i, n in enumerate(nums)) / den
             for nums, den in zip(new['hecke_ring_numerators'], new['hecke_ring_denominators'])]
    for x, v in zip(lambda_p + lambda_p_square, new['lambda_p'] + new['lambda_p_square']):
        if x != 'NULL':
            assert sum(c * b for c, b in zip(v, basis)) == x, N
    record = {'hecke_ring_disc_factorization': ([[-1, 1]] if dH < 0 else []) + [[int(p), int(e)] for p, e in fac],
              'field_disc': int(dK), 'field_disc_factorization': fdisc, 'polredabs': red}
    return new, record


def process(N, rundir, datadir, outdir):
    ps = prime_range(B)
    sq_ps = prime_range(sqrt(B))
    fname = os.path.join(datadir, "hecke_ev_3_0_%d.dat" % N)
    with open(fname) as f:
        newline = f.read().endswith("\n")
    entries = load(fname)
    forms = run_forms(os.path.join(rundir, "%d.dat" % N), N)
    records = []
    for idx, e in enumerate(entries):
        dim = len(e['field_poly']) - 1
        if e['aut_rep_type'] != 'G' or e.get('lambda_p') or not MIN_DEG <= dim <= MAX_DEG:
            continue
        t0 = time.time()
        # (the stored Atkin-Lehner signs are those of the paramodular form, not the spinor conductor of the run)
        m = [f for f in forms if f[0] == e['field_poly']
             and [int(f[2][p].trace()) if p in f[2] else 'NULL' for p in ps] == e['trace_lambda_p']]
        assert len(m) == 1, "level %d: %d forms of the run for an orbit of dimension %d" % (N, len(m), dim)
        coeffs, F, lp, lp2 = m[0]
        lambda_p = ['NULL' if N % p == 0 else lp[p] for p in ps]
        lambda_p_square = ['NULL' if N % p == 0 else lp2[p] for p in sq_ps]
        tr2 = ['NULL' if x == 'NULL' else int(x.trace()) for x in lambda_p_square]
        assert tr2 == e['trace_lambda_p_square'], "level %d: traces of T(p,2) differ" % N
        new, record = orbit_data(N, F, lambda_p, lambda_p_square)
        for k in ['field_poly', 'atkin_lehner_eigenvals', 'trace_lambda_p', 'aut_rep_type', 'atkin_lehner_string',
                  'trace_lambda_p_square']:
            new[k] = e[k]
        entries[idx] = {k: new[k] for k in KEYS}
        records.append(dict({'level': N, 'field_poly': e['field_poly']}, **record))
        print("level %d: orbit %d of dimension %d, index %d, nbound %d, disc(H) %d digits (%.1fs)"
              % (N, idx, dim, new['hecke_ring_index'], new['hecke_ring_generator_nbound'],
                 len(str(abs(ZZ(record['field_disc'])) * new['hecke_ring_index']**2)), time.time() - t0), flush=True)
    with open(os.path.join(outdir, "hecke_ev_3_0_%d.dat" % N), "w") as f:
        f.write(str(entries) + ("\n" if newline else ""))
    with open(os.path.join(outdir, "fields_%d.json" % N), "w") as f:
        json.dump(records, f)
    return len(records)


if __name__ == '__main__':
    rundir, datadir, outdir = sys.argv[1:4]
    total = 0
    for N in map(int, sys.argv[4:]):
        total += process(N, rundir, datadir, outdir)
    print("orbits given coordinates:", total)
