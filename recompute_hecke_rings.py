"""
Recompute the Hecke ring of the orbits of omf5_data that have eigenvalue coordinates.

parse_omf5 (omf5/scripts/parse_omf.py) tested whether the first eigenvalues
generate an order by the rank of their Z-span, which is at most 5; so for degree
>= 6 (and mostly for degree 5) it fell back to the ring of integers, stored as
the Hecke ring with index 1 and nbound 0.  Here the Hecke ring H is the order
generated by all the stored eigenvalues (lambda_p, p < 100, and lambda_p_square).
They lie in the stored basis, which is an order of index hecke_ring_index in the
ring of integers, so

    hecke_ring_index = stored index * [stored order : H],

with no ring of integers to compute.  hecke_ring_generator_nbound is the smallest
n such that the eigenvalues lambda_j with j <= n generate H, where lambda_j is
lambda_p for j = p and lambda_p_square for j = p^2 (bad primes skipped, and
n = 1 when H = Z, generated by lambda_1 = 1); so reproducing H needs
lambda_p_square only for p <= sqrt(n).  The basis of H is
Sage's basis of the order, as in parse_omf5, and the coordinates are rewritten
in it.  Entries whose Hecke ring is the stored one are unchanged.

    sage -python recompute_hecke_rings.py DATADIR OUTDIR N [N ...]

Prints one line per changed orbit, and per level a summary line.
"""
import os
import re
import sys

from sage.all import Matrix, QQ, ZZ, NumberField, polygen, prime_range, vector
from rebasis_hecke_rings import reduced_basis


def load(fname):
    with open(fname) as f:
        return eval(re.sub(r'(\d)L', r'\1', f.read()))


def closure(rows, mult):
    """The Z-module (HNF rows) of the ring generated by 1 and the vectors rows."""
    M = Matrix(ZZ, rows).echelon_form()
    M = [r for r in M.rows() if r]
    while True:
        new = Matrix(ZZ, [mult(u, v) for i, u in enumerate(M) for v in M[i:]] + M).echelon_form()
        new = [r for r in new.rows() if r]
        if new == M:
            return M
        M = new


def recompute(e):
    """The entry with its Hecke ring recomputed, and a description of the change (None if unchanged)."""
    d = len(e['field_poly']) - 1
    x = polygen(QQ)
    F = NumberField(sum(c * x**i for i, c in enumerate(e['field_poly'])), 'a')
    a = F.gen()
    B = [sum(n * a**i for i, n in enumerate(nums)) / den
         for nums, den in zip(e['hecke_ring_numerators'], e['hecke_ring_denominators'])]
    Bmat = Matrix(QQ, [list(b) for b in B])
    Binv = Bmat**(-1)

    def coords(y):
        v = vector(QQ, list(y)) * Binv
        assert all(c in ZZ for c in v)
        return vector(ZZ, v)

    def elt(v):
        return sum(c * b for c, b in zip(v, B))

    def mult(u, v):
        return coords(elt(u) * elt(v))

    one = coords(F(1))
    ps = prime_range(100)
    lamj = sorted([(p, vector(ZZ, v)) for p, v in zip(ps, e['lambda_p']) if v != 'NULL'] +
                  [(p * p, vector(ZZ, v)) for p, v in zip(ps, e['lambda_p_square']) if v != 'NULL'],
                  key=lambda t: t[0])
    H_lam = closure([one] + [v for j, v in lamj if j in ps], mult)
    H = closure([one] + [v for _, v in lamj], mult)
    assert len(H) == d, "the eigenvalues do not generate an order"
    rel = abs(Matrix(ZZ, H).det())      # [stored order : H]
    # nbound: the smallest n such that the lambda_j with j <= n generate H
    nbound, M = 1, [one]
    for j, v in lamj:
        if len(M) == d and abs(Matrix(ZZ, M).det()) == rel:
            break
        M = closure(M + [v], mult)
        nbound = j
    assert len(M) == d and abs(Matrix(ZZ, M).det()) == rel
    index = e['hecke_ring_index'] * rel
    info = {'deg': d, 'old_index': e['hecke_ring_index'], 'index': int(index),
            'old_nbound': e['hecke_ring_generator_nbound'], 'nbound': int(nbound),
            'squares_needed': H != H_lam}
    if rel == 1 and nbound == e['hecke_ring_generator_nbound']:
        return e, None
    if rel == 1:
        new = dict(e)
        new['hecke_ring_generator_nbound'] = int(nbound)
        return new, info
    # a basis of H starting with 1, reduced against lambda_p (rebasis_hecke_rings.reduced_basis)
    mat = reduced_basis(Matrix(QQ, [list(elt(r)) for r in H]), [vector(QQ, list(elt(v))) for j, v in lamj if j in ps])
    inv = mat**(-1)
    new = dict(e)     # keeps the key order
    new['hecke_ring_index'] = int(index)
    new['hecke_ring_generator_nbound'] = int(nbound)
    new['hecke_ring_denominators'] = [int(r.denominator()) for r in mat]
    new['hecke_ring_numerators'] = [[int(c) for c in r.denominator() * r] for r in mat]
    new['hecke_ring_inverse_denominators'] = [int(r.denominator()) for r in inv]
    new['hecke_ring_inverse_numerators'] = [[int(c) for c in r.denominator() * r] for r in inv]

    def to_new(v):
        if v == 'NULL':
            return 'NULL'
        w = (Matrix(QQ, [list(elt(vector(ZZ, v)))]) * inv).row(0)
        assert all(c in ZZ for c in w), "an eigenvalue is not in the Hecke ring"
        return [int(c) for c in w]
    new['lambda_p'] = [to_new(v) for v in e['lambda_p']]
    new['lambda_p_square'] = [to_new(v) for v in e['lambda_p_square']]
    # the new coordinates give the same eigenvalues
    Bn = [sum(n * a**i for i, n in enumerate(nums)) / den
          for nums, den in zip(new['hecke_ring_numerators'], new['hecke_ring_denominators'])]
    for old, nw in zip(e['lambda_p'] + e['lambda_p_square'], new['lambda_p'] + new['lambda_p_square']):
        if old != 'NULL':
            assert elt(vector(ZZ, old)) == sum(c * b for c, b in zip(nw, Bn))
    return new, info


def process(N, datadir, outdir):
    fname = os.path.join(datadir, "hecke_ev_3_0_%d.dat" % N)
    with open(fname) as f:
        newline = f.read().endswith("\n")
    entries = load(fname)
    changed = 0
    for idx, e in enumerate(entries):
        if not e.get('lambda_p'):
            continue
        new, info = recompute(e)
        if info is not None:
            entries[idx] = new
            changed += 1
            print("level %d orbit %d: %s" % (N, idx, info), flush=True)
    if changed:
        with open(os.path.join(outdir, "hecke_ev_3_0_%d.dat" % N), "w") as f:
            f.write(str(entries) + ("\n" if newline else ""))
    print("level %d: %d changed" % (N, changed), flush=True)


if __name__ == '__main__':
    datadir, outdir = sys.argv[1:3]
    for N in map(int, sys.argv[3:]):
        process(N, datadir, outdir)
