"""
Check hecke_evs_3_0/fields.json against hecke_evs_3_0/data, without factoring anything.

For the orbits of dimension 14-20 the ring of integers was not computed by
factoring the discriminant of field_poly (which is disc(O_K) [O_K : Z[a]]^2 and
has hundreds of digits) but from the factorization of the discriminant of the
Hecke ring H, which is disc(O_K) [O_K : H]^2 and has at most 85 digits.
fields.json records that factorization as a certificate.  For each record this
script checks that:

  - the orbit is in the data, with the Hecke ring basis and coordinates;
  - the coordinates are those of an order: the stored basis spans the ring
    generated by the stored eigenvalues (so it is the Hecke ring), and
    hecke_ring_generator_nbound is as described in recompute_hecke_rings.py;
  - hecke_ring_disc_factorization multiplies to disc(H), and its primes are
    proved prime;
  - O_K, the ring generated by H and pari's nfbasis([f, P]) for P the primes p
    with p^2 | disc(H), is maximal at P (by nfbasis) and at every other prime
    (where H already is), so it is the ring of integers;
  - hecke_ring_index = [O_K : H], and field_disc, field_disc_factorization and
    polredabs are those of O_K (pari's nfinit([f, basis of O_K])).

    sage -python verify_fields.py [hecke_evs_3_0]
"""
import json
import os
import re
import sys

from sage.all import Matrix, QQ, ZZ, NumberField, lcm, pari, polygen, prime_range, prod, vector


def load(fname):
    with open(fname) as f:
        return eval(re.sub(r'(\d)L', r'\1', f.read()))


def hnf(rows):
    D = lcm([c.denominator() for r in rows for c in r])
    M = (Matrix(QQ, rows) * D).change_ring(ZZ).echelon_form()
    return [vector(QQ, r) / D for r in M.rows() if r]


def ring_closure(F, rows):
    """Rows over QQ (power basis) of a Z-basis of the ring generated by 1 and the elements rows."""
    M = hnf([vector(QQ, list(F(1)))] + [vector(QQ, list(r)) for r in rows])
    while True:
        els = [F(list(r)) for r in M]
        new = hnf([vector(QQ, list(u * v)) for i, u in enumerate(els) for v in els[i:]] + M)
        if new == M:
            return M
        M = new


def disc(F, rows):
    els = [F(list(r)) for r in rows]
    return ZZ(Matrix(QQ, [[(x * y).trace() for y in els] for x in els]).det())


def triangular(rows):
    """The same lattice, with a basis b_0 = 1, b_1, ... in which b_i has degree i (as pari's nfinit wants)."""
    d = len(rows)
    D = lcm([c.denominator() for r in rows for c in r])
    M = Matrix(ZZ, [[ZZ(c * D) for c in reversed(list(r))] for r in rows]).echelon_form()
    out = [vector(QQ, list(reversed(list(r)))) / D for r in reversed(M.rows())]
    assert out[0] == vector(QQ, [1] + [0] * (d - 1))
    return out


def check(r, e):
    x = polygen(QQ)
    F = NumberField(sum(c * x**i for i, c in enumerate(e['field_poly'])), 'a')
    a = F.gen()
    d = F.degree()
    basis = [sum(n * a**i for i, n in enumerate(nums)) / den
             for nums, den in zip(e['hecke_ring_numerators'], e['hecke_ring_denominators'])]
    H = hnf([vector(QQ, list(b)) for b in basis])
    ps = prime_range(100)
    lamj = sorted([(p, sum(c * b for c, b in zip(v, basis))) for p, v in zip(ps, e['lambda_p']) if v != 'NULL'] +
                  [(p * p, sum(c * b for c, b in zip(v, basis))) for p, v in zip(ps, e['lambda_p_square'])
                   if v != 'NULL'], key=lambda t: t[0])
    assert ring_closure(F, [list(y) for _, y in lamj]) == H, "the basis is not the Hecke ring"
    nbound, M = 1, ring_closure(F, [])
    for j, y in lamj:
        if M == H:
            break
        M = ring_closure(F, M + [list(y)])
        nbound = j
    assert nbound == e['hecke_ring_generator_nbound'], "nbound"
    dH = disc(F, H)
    fac = r['hecke_ring_disc_factorization']
    assert prod(ZZ(p)**k for p, k in fac) == dH, "the factorization does not multiply to disc(H)"
    for p, k in fac:
        assert p == -1 or ZZ(p).is_prime(proof=True), "%d is not prime" % p
    P = [p for p, k in fac if p != -1 and k >= 2]
    OK = H
    if P:
        O1 = [vector(QQ, [QQ(c) for c in pari(b).Vecrev()] + [0] * (d - len(pari(b).Vecrev())))
              for b in pari.nfbasis([pari(F.polynomial()), P])]
        OK = ring_closure(F, O1 + H)
    dK = disc(F, OK)
    assert ZZ(r['field_disc']) == dK, "field_disc"
    assert ZZ(e['hecke_ring_index'])**2 * dK == dH, "hecke_ring_index"
    fd = r['field_disc_factorization']
    assert prod(ZZ(p)**k for p, k in fd) == dK and all(p in [q for q, _ in fac] for p, k in fd), "field_disc_factorization"
    nf = pari.nfinit([pari(F.polynomial()), pari([pari(F(list(b)).polynomial()) for b in triangular(OK)])])
    assert ZZ(pari('(x) -> x.disc')(nf)) == dK
    assert [int(c) for c in pari(pari.polredabs(nf)).Vecrev()] == r['polredabs'], "polredabs"


if __name__ == '__main__':
    folder = sys.argv[1] if len(sys.argv) > 1 else 'hecke_evs_3_0'
    with open(os.path.join(folder, 'fields.json')) as f:
        records = json.load(f)
    data = {}
    for r in records:
        N = r['level']
        if N not in data:
            data[N] = load(os.path.join(folder, 'data', 'hecke_ev_3_0_%d.dat' % N))
        m = [e for e in data[N] if e['field_poly'] == r['field_poly'] and e['trace_lambda_p'] == r['trace_lambda_p']]
        assert len(m) == 1 and m[0].get('lambda_p'), "level %d: the orbit of a record is not in the data" % N
        check(r, m[0])
    print("%d records checked" % len(records))
