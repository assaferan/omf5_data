"""
Recompute the Hecke ring of the orbits of hecke_evs_3_0/data_nl_200.

As recompute_hecke_rings.py does for hecke_evs_3_0/data: the Hecke ring H is the order
generated by all the stored eigenvalues (here lambda_p for p < 200 and lambda_p_square
for p <= 13).  The difference is that here an eigenvalue need not lie in the stored
order: parse_omf5 took the order spanned by the first few lambda_p, and in 137 orbits
the later eigenvalues have fractional coordinates in it.  (They are the true eigenvalues:
for p < 100 they agree with hecke_evs_3_0/data.)  So everything is done in the power
basis of the field, with rational lattices.

For each orbit with coordinates:
  - H is the closure under multiplication of the Z-span of 1 and the eigenvalues;
  - hecke_ring_index = stored index * [stored order : H] (a ratio of covolumes, which
    must be an integer), checked against the maximal order whenever PARI finds it
    within MAXORDER_SECONDS;
  - hecke_ring_generator_nbound is the smallest n such that the lambda_j with j <= n
    generate H (j = p for lambda_p, j = p^2 for lambda_p_square; 1 when H = Z);
  - if H is not the stored order, its basis is rebasis_hecke_rings.reduced_basis (starting
    with 1, reduced against the lambda_p) and the coordinates are rewritten in it,
    checking that every eigenvalue is the same field element and has integer coordinates.

    sage -python recompute_nl_200_rings.py DATADIR [N ...]      # all levels by default

Prints one line per changed orbit and a summary.
"""
import glob
import os
import re
import sys
from collections import Counter

from sage.all import (Matrix, QQ, ZZ, NumberField, alarm, cancel_alarm, identity_matrix, lcm, polygen,
                      prime_range, vector)
from rebasis_hecke_rings import as_cols, dump, load, reduced_basis, rows_of

MAXORDER_SECONDS = 20


def hnf(rows, d):
    """The Hermite normal form of the lattice spanned by the rational vectors rows, as a rational matrix
    without zero rows."""
    rows = [vector(QQ, r) for r in rows]
    D = lcm([c.denominator() for r in rows for c in r])
    M = Matrix(ZZ, len(rows), d, [[ZZ(c * D) for c in r] for r in rows]).echelon_form()
    return Matrix(QQ, [r for r in M.rows() if r]) / D


def closure(rows, F, d):
    """The HNF of the ring generated by the rows (field elements in the power basis)."""
    M = hnf(rows, d)
    while True:
        elts = [F(list(r)) for r in M.rows()]
        new = hnf([vector(QQ, list(u * v)) for i, u in enumerate(elts) for v in elts[i:]] + M.rows(), d)
        if new == M:
            return M
        M = new


def maximal_order_matrix(F):
    try:
        alarm(MAXORDER_SECONDS)
        B = F.maximal_order().basis()
        cancel_alarm()
    except (KeyboardInterrupt, Exception):    # AlarmInterrupt is a KeyboardInterrupt
        cancel_alarm()
        return None
    return Matrix(QQ, [list(b) for b in B])


def recompute(e, stats):
    """The entry with its Hecke ring recomputed, and a description of the change (None if unchanged)."""
    d = len(e['field_poly']) - 1
    x = polygen(QQ)
    F = NumberField(sum(c * x**i for i, c in enumerate(e['field_poly'])), 'a') if d > 1 else QQ
    one = vector(QQ, [1] + [0] * (d - 1))
    if e.get('hecke_ring_numerators'):
        B = rows_of(e['hecke_ring_numerators'], e['hecke_ring_denominators'])
    else:
        assert e['hecke_ring_power_basis']
        B = identity_matrix(QQ, d)

    def elt(v):
        return vector(QQ, [QQ(c) for c in v]) * B

    ps = prime_range(200)
    assert len(e['lambda_p']) == len(ps) and len(e['lambda_p_square']) <= len(ps)
    lamj = sorted([(p, elt(v)) for p, v in zip(ps, e['lambda_p']) if v != 'NULL'] +
                  [(p * p, elt(v)) for p, v in zip(ps, e['lambda_p_square']) if v != 'NULL'],
                  key=lambda t: t[0])
    if d == 1:
        H = Matrix(QQ, [[1]])
        assert all(v[0] in ZZ for _, v in lamj)
    else:
        H = closure([one] + [v for _, v in lamj], F, d)
    assert H.nrows() == d, "the eigenvalues do not generate an order"
    ratio = abs(H.det() / B.det())      # [stored order : H], which is 1/[H : stored order] when H is larger
    index = e['hecke_ring_index'] * ratio
    OK = maximal_order_matrix(F) if d > 1 else Matrix(QQ, [[1]])
    if OK is None:
        stats['index not checked against the maximal order'] += 1
    else:
        direct = abs(H.det() / OK.det())
        if direct != index:
            stats['stored index was not that of the stored order'] += 1
            index = direct
    assert index in ZZ and index >= 1, "index %s" % index
    # nbound: the smallest n such that the lambda_j with j <= n generate H
    nbound, M = 1, Matrix(QQ, [one])
    for j, v in lamj:
        if M == H:
            break
        if hnf(M.rows() + [v], d) != M:
            M = closure(M.rows() + [v], F, d)
        nbound = j
    assert M == H
    same_ring = hnf(B.rows(), d) == H
    info = {'deg': d, 'old_index': e['hecke_ring_index'], 'index': int(index),
            'old_nbound': e['hecke_ring_generator_nbound'], 'nbound': int(nbound), 'ring': 'same' if same_ring else
            ('larger' if ratio < 1 and all(c in ZZ for c in (B * H.inverse()).list()) else
             'smaller' if all(c in ZZ for c in (H * B.inverse()).list()) else 'other')}
    if same_ring and index == e['hecke_ring_index'] and nbound == e['hecke_ring_generator_nbound']:
        return e, None
    new = dict(e)     # keeps the key order
    new['hecke_ring_index'] = int(index)
    new['hecke_ring_generator_nbound'] = int(nbound)
    if same_ring:
        return new, info
    T = reduced_basis(H, [v for j, v in lamj if j in ps])
    Tinv = T.inverse()
    assert hnf(T.rows(), d) == H and T.row(0) == one
    new['hecke_ring_power_basis'] = bool(T == 1)
    new['hecke_ring_numerators'], new['hecke_ring_denominators'] = as_cols(T)
    new['hecke_ring_inverse_numerators'], new['hecke_ring_inverse_denominators'] = as_cols(Tinv)
    for col in ('lambda_p', 'lambda_p_square'):
        out = []
        for v in e[col]:
            if v == 'NULL':
                out.append(v)
                continue
            w = elt(v) * Tinv
            assert all(c in ZZ for c in w), "an eigenvalue is not in the Hecke ring"
            assert w * T == elt(v)
            out.append([int(c) for c in w])
        new[col] = out
    return new, info


def process(fname, stats):
    N = int(re.search(r'_(\d+)\.dat$', fname).group(1))
    with open(fname) as f:
        text = f.read()
    nl = "\n" if text.endswith("\n") else ""
    entries = load(text)
    changed = 0
    for idx, e in enumerate(entries):
        if not e.get('lambda_p'):
            continue
        stats['orbits with coordinates'] += 1
        new, info = recompute(e, stats)
        if info is not None:
            entries[idx] = new
            changed += 1
            stats['changed'] += 1
            stats['ring ' + info['ring']] += 1
            print("level %d orbit %d: %s" % (N, idx, info), flush=True)
    if changed:
        assert dump(load(text)) + nl == text, "%s is not reproduced from what was read" % fname
        with open(fname, 'w') as f:
            f.write(dump(entries) + nl)


if __name__ == '__main__':
    datadir = sys.argv[1]
    levels = set(map(int, sys.argv[2:]))
    stats = Counter()
    for fname in sorted(glob.glob(os.path.join(datadir, 'hecke_ev_3_0_nl_200_*.dat'))):
        if not levels or int(re.search(r'_(\d+)\.dat$', fname).group(1)) in levels:
            process(fname, stats)
    print(dict(stats), flush=True)
